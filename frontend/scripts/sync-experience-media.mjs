import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const json = JSON.parse(fs.readFileSync(path.join(ROOT, 'src/pages/PlanBuilder/data/experienceMedia.json'), 'utf8'))
const body = `/** Auto-generated by scripts/fetch-experience-media.mjs — do not edit by hand. */
export type ExperienceVideo = {
  youtubeId: string
  title?: string
}

export type ExperienceMedia = {
  photos: string[]
  videos: ExperienceVideo[]
}

export const EXPERIENCE_MEDIA: Record<string, ExperienceMedia> = ${JSON.stringify(json, null, 2)}

export function getExperienceMedia(id: string): ExperienceMedia | null {
  return EXPERIENCE_MEDIA[id] ?? null
}
`
fs.writeFileSync(path.join(ROOT, 'src/pages/PlanBuilder/data/experienceMedia.ts'), body)
console.log('synced', Object.keys(json).length, 'media entries')
