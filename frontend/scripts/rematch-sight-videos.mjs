/**
 * Re-score existing sight videos and replace mismatches via YouTube search.
 * Run: node scripts/rematch-sight-videos.mjs
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(__dirname, '..')
const DATA_DIR = path.join(ROOT, 'src', 'pages', 'PlanBuilder', 'data')
const OUT_JSON = path.join(DATA_DIR, 'experienceMedia.json')
const OUT_TS = path.join(DATA_DIR, 'experienceMedia.ts')

const STOP = new Set([
  'the', 'and', 'of', 'a', 'an', 'in', 'at', 'for', 'to', 'with', 'from', 'day',
  'walk', 'evening', 'morning', 'afternoon', 'class', 'tour', 'crawl', 'corner',
  'circuit', 'complex', 'escape', 'viewpoint', 'peak', 'section', 'hidden',
  'vietnam', 'viet', 'nam', 'landscape', 'scenic',
])

const GENERIC_LIST =
  /\b(things to do|places to visit|best places|top\s*\d+|must[- ]see|bucket list|itinerary|\d+\s*days?\s+in|vlog|nightcore|trendingvideo|clickbait|you won'?t believe|compilation|travel guide to vietnam)\b/i
const COMBO_COMPARE = /\bvs\.?\b|\bversus\b|\bcompared to\b/i

function tokens(name) {
  return name
    .replace(/\([^)]*\)/g, ' ')
    .toLowerCase()
    .replace(/[^a-z0-9\sàáảãạăằắẩẵặâầấẩẫậèéẻẽẹêềếểễệìíỉĩịòóỏõọôồốổỗộơờớởỡợùúủũụưừứửữựỳýỷỹỵđ]/gi, ' ')
    .split(/\s+/)
    .filter((w) => w.length > 2 && !STOP.has(w))
}

function distinctivePhrase(name) {
  return name.replace(/\([^)]*\)/g, ' ').replace(/\s+/g, ' ').trim().toLowerCase()
}

function corePhrase(name) {
  const words = name
    .replace(/\([^)]*\)/g, ' ')
    .trim()
    .split(/\s+/)
    .filter((w) => !['the', 'of', 'and', 'a', 'an'].includes(w.toLowerCase()))
  return words.slice(0, 2).join(' ').toLowerCase()
}

function includesAll(haystack, parts) {
  return parts.length > 0 && parts.every((p) => haystack.includes(p))
}

function titleMatches(title, sight, catalog) {
  const t = (title ?? '').toLowerCase().replace(/#\w+/g, ' ')
  if (!t.trim()) return false
  if (COMBO_COMPARE.test(t)) return false
  if (GENERIC_LIST.test(t)) return false
  if (/\b(shocked|accident|you won'?t believe|clickbait|must watch|hotel review)\b/i.test(t)) return false
  if (/\d+\s*km walk/i.test(t)) return false

  const aliases = [sight.name, ...(sight.aliases ?? [])]
  const nameHit =
    aliases.some((alias) => {
      const toks = tokens(alias)
      if (!toks.length) return false
      const needed = toks.length <= 2 ? toks.length : Math.ceil(toks.length * 0.75)
      return toks.filter((tok) => t.includes(tok)).length >= needed
    }) ||
    (() => {
      const core = corePhrase(sight.name)
      return core.length >= 7 && t.includes(core)
    })()
  if (!nameHit) return false

  const selfPhrase = distinctivePhrase(sight.name)
  for (const other of catalog) {
    if (other.id === sight.id) continue
    const otherPhrase = distinctivePhrase(other.name)
    if (otherPhrase.length < 8) continue
    const selfCore = corePhrase(sight.name)
    const otherCore = corePhrase(other.name)
    if (selfCore && selfCore === otherCore) continue
    if (selfPhrase.includes(otherPhrase) || otherPhrase.includes(selfPhrase)) continue
    const otherToks = tokens(other.name)
    if (otherToks.length < 2) continue
    if (includesAll(t, otherToks) && !includesAll(selfPhrase, otherToks)) return false
  }
  return true
}

function parseExperiences() {
  const files = [
    'experiences.ts',
    'experiencesExtra.ts',
    'experiencesHoiAn.ts',
    'experiencesNinhBinh.ts',
    'experiencesDaLat.ts',
    'experiencesHue.ts',
    'experiencesSapa.ts',
    'experiencesPhuQuoc.ts',
    'experiencesHaLong.ts',
    'experiencesPhongNha.ts',
    'experiencesNhaTrang.ts',
    'experiencesCanTho.ts',
    'experiencesHaGiang.ts',
    'experiencesCatBa.ts',
    'experiencesDongVan.ts',
  ]
  const list = []
  const blobs = []
  for (const file of files) {
    const text = fs.readFileSync(path.join(DATA_DIR, file), 'utf8')
    blobs.push(text)
    const cityConst = text.match(/city: '([^']+)' as const/)
    const regionConst = text.match(/region: '([^']+)' as const/)
    const re = /id: '([^']+)',\s*\n\s*name: '([^']+)',(?:\s*\n\s*region: '([^']+)',\s*\n\s*city: '([^']+)')?/g
    let m
    while ((m = re.exec(text))) {
      list.push({
        id: m[1],
        name: m[2],
        region: m[3] ?? regionConst?.[1] ?? cityConst?.[1] ?? '',
        city: m[4] ?? cityConst?.[1] ?? m[3] ?? '',
      })
    }
  }
  return list
}

function writeTs(media) {
  const body = `/** Auto-generated by scripts/fetch-experience-media.mjs — do not edit by hand. */
export type ExperienceVideo = {
  youtubeId: string
  title?: string
}

export type ExperienceMedia = {
  photos: string[]
  videos: ExperienceVideo[]
}

export const EXPERIENCE_MEDIA: Record<string, ExperienceMedia> = ${JSON.stringify(media, null, 2)}

export function getExperienceMedia(id: string): ExperienceMedia | null {
  return EXPERIENCE_MEDIA[id] ?? null
}
`
  fs.writeFileSync(OUT_TS, body, 'utf8')
}

async function youtubeSearch(query) {
  const res = await fetch('https://www.youtube.com/youtubei/v1/search?prettyPrint=false', {
    method: 'POST',
    headers: {
      'content-type': 'application/json',
      'user-agent':
        'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/122.0.0.0 Safari/537.36',
    },
    body: JSON.stringify({
      context: {
        client: {
          clientName: 'WEB',
          clientVersion: '2.20240101.00.00',
          hl: 'en',
          gl: 'US',
        },
      },
      query,
    }),
  })
  if (!res.ok) return []
  const json = await res.json()
  const out = []
  const seen = new Set()
  const walk = (node) => {
    if (!node || typeof node !== 'object') return
    const vid = node.videoId
    const title =
      node.title?.runs?.map((r) => r.text).join('') ||
      node.title?.simpleText ||
      node.headline?.simpleText
    if (vid && title && !seen.has(vid) && vid.length === 11) {
      seen.add(vid)
      out.push({ youtubeId: vid, title: String(title).replace(/\s+/g, ' ').trim() })
    }
    for (const v of Object.values(node)) {
      if (Array.isArray(v)) v.forEach(walk)
      else if (v && typeof v === 'object') walk(v)
    }
  }
  walk(json)
  return out.slice(0, 16)
}

async function findVideos(sight, catalog) {
  const queries = [
    `"${sight.name}" ${sight.city} Vietnam walking`,
    `"${sight.name}" ${sight.city} visit`,
    `${sight.name} ${sight.city} Vietnam`,
  ]
  const pool = []
  for (const q of queries) {
    const batch = await youtubeSearch(q)
    for (const item of batch) {
      if (!pool.some((p) => p.youtubeId === item.youtubeId)) pool.push(item)
    }
    await new Promise((r) => setTimeout(r, 400))
    const matched = pool.filter((v) => titleMatches(v.title, sight, catalog))
    if (matched.length >= 2) return matched.slice(0, 2)
  }
  return pool.filter((v) => titleMatches(v.title, sight, catalog)).slice(0, 2)
}

async function main() {
  const catalog = parseExperiences()
  const media = JSON.parse(fs.readFileSync(OUT_JSON, 'utf8'))
  const limit = process.env.LIMIT ? Number(process.env.LIMIT) : catalog.length
  const slice = catalog.slice(0, limit)
  let replaced = 0
  let kept = 0
  let empty = 0

  for (let i = 0; i < slice.length; i++) {
    const sight = slice[i]
    const entry = media[sight.id] ?? { photos: [], videos: [] }
    const good = (entry.videos ?? []).filter((v) => titleMatches(v.title, sight, catalog))
    if (process.env.FILTER_ONLY) {
      if (good.length !== (entry.videos ?? []).length) replaced += 1
      else kept += 1
      if (!good.length) empty += 1
      entry.videos = good.slice(0, 2)
      media[sight.id] = entry
      continue
    }
    if (good.length >= 1 && !process.env.FORCE) {
      entry.videos = good.slice(0, 2)
      media[sight.id] = entry
      kept += 1
      continue
    }
    process.stdout.write(`[${i + 1}/${slice.length}] ${sight.id} … `)
    const found = await findVideos(sight, catalog)
    if (found.length) {
      entry.videos = found
      replaced += 1
      console.log(found[0].title.slice(0, 80))
    } else {
      entry.videos = good
      empty += 1
      console.log(good.length ? 'kept filtered' : 'NO MATCH')
    }
    media[sight.id] = entry
    if (i % 20 === 0) {
      fs.writeFileSync(OUT_JSON, JSON.stringify(media, null, 2), 'utf8')
    }
  }

  fs.writeFileSync(OUT_JSON, JSON.stringify(media, null, 2), 'utf8')
  writeTs(media)
  console.log(`Done. kept=${kept} replaced=${replaced} empty=${empty}`)
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
