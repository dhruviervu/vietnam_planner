/**
 * Pad high-ROI sights to 8–10 Commons photos that match the place name.
 * Run: node scripts/pad-high-roi-photos.mjs
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(__dirname, '..')
const DATA_DIR = path.join(ROOT, 'src', 'pages', 'PlanBuilder', 'data')
const OUT_JSON = path.join(DATA_DIR, 'experienceMedia.json')
const OUT_TS = path.join(DATA_DIR, 'experienceMedia.ts')
const UA = 'VietnamPlannerMediaBot/1.2 (travel planner; local research)'
const WANT = 10

function fold(s) {
  return String(s || '')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, ' ')
    .trim()
}

function sleep(ms) {
  return new Promise((r) => setTimeout(r, ms))
}

function cleanUrl(url) {
  return String(url || '').split('?')[0]
}

function photoScore(title, exp) {
  const t = fold(title)
  const name = fold(exp.name)
  const tokens = name.split(' ').filter((w) => w.length > 2)
  let s = 0
  for (const tok of tokens) if (t.includes(tok)) s += tok.length >= 5 ? 3 : 2
  if (t.includes(fold(exp.city))) s += 1
  if (t.includes('vietnam')) s += 0.5
  if (tokens.length && tokens.filter((tok) => t.includes(tok)).length < Math.min(2, tokens.length)) {
    s -= 4
  }
  return s
}

async function commonsSearch(query, limit = 24) {
  const params = new URLSearchParams({
    action: 'query',
    generator: 'search',
    gsrsearch: `${query} filetype:bitmap`,
    gsrnamespace: '6',
    gsrlimit: String(limit),
    prop: 'imageinfo',
    iiprop: 'url|mime|size',
    iiurlwidth: '1280',
    format: 'json',
    origin: '*',
  })
  const res = await fetch(`https://commons.wikimedia.org/w/api.php?${params}`, {
    headers: { 'User-Agent': UA },
  })
  if (!res.ok) return []
  const json = await res.json()
  const out = []
  for (const page of Object.values(json?.query?.pages ?? {})) {
    const info = page.imageinfo?.[0]
    if (!info?.thumburl) continue
    if (info.mime?.startsWith('video/')) continue
    out.push({ url: cleanUrl(info.thumburl), title: page.title ?? '' })
  }
  return out
}

function writeTs(media) {
  const body = `/** Auto-generated by scripts/fetch-experience-media.mjs — do not edit by hand. */
export type ExperienceVideo = {
  youtubeId: string
  title?: string
}

export type ExperienceMedia = {
  photos: string[]
  videos: ExperienceVideo[]
}

export const EXPERIENCE_MEDIA: Record<string, ExperienceMedia> = ${JSON.stringify(media, null, 2)}

export function getExperienceMedia(id: string): ExperienceMedia | null {
  return EXPERIENCE_MEDIA[id] ?? null
}
`
  fs.writeFileSync(OUT_TS, body, 'utf8')
}

const { SIGHT_CATALOG } = await import('../src/pages/PlanBuilder/data/experiences.ts')
const { highRoiCatalogSights } = await import('../src/pages/PlanBuilder/lib/highRoiSights.ts')
const { getExperienceImages } = await import('../src/pages/PlanBuilder/lib/pricing.ts')
const { isGenericCityPhoto } = await import('../src/pages/PlanBuilder/lib/resolveCatalogPhotos.ts')

const media = fs.existsSync(OUT_JSON) ? JSON.parse(fs.readFileSync(OUT_JSON, 'utf8')) : {}
const targets = highRoiCatalogSights(SIGHT_CATALOG)
let padded = 0

for (const exp of targets) {
  const current = (getExperienceImages(exp) || []).filter((url) => !isGenericCityPhoto(url, exp))
  if (current.length >= 8) continue
  const queries = [
    `"${exp.name}" ${exp.city}`,
    `${exp.name} ${exp.city} Vietnam`,
    `${exp.name} Vietnam`,
    exp.name,
  ]
  const seen = new Set(current.map(cleanUrl))
  const added = []
  for (const q of queries) {
    if (seen.size >= WANT) break
    const hits = await commonsSearch(q)
    await sleep(220)
    for (const hit of hits) {
      if (seen.has(hit.url)) continue
      if (photoScore(hit.title, exp) < 2) continue
      if (isGenericCityPhoto(hit.url, exp)) continue
      seen.add(hit.url)
      added.push(hit.url)
      if (seen.size >= WANT) break
    }
  }
  const photos = [...current, ...added].slice(0, WANT)
  if (photos.length <= current.length && added.length === 0) {
    console.log(`[skip] ${exp.id} still ${current.length}`)
    continue
  }
  media[exp.id] = {
    photos,
    videos: media[exp.id]?.videos ?? [],
  }
  padded += 1
  console.log(`[pad] ${exp.id} ${current.length} → ${photos.length} (+${added.length})`)
  if (padded % 5 === 0) {
    fs.writeFileSync(OUT_JSON, JSON.stringify(media, null, 2), 'utf8')
  }
}

fs.writeFileSync(OUT_JSON, JSON.stringify(media, null, 2), 'utf8')
writeTs(media)
console.log(`Done. Padded ${padded} high-ROI sights.`)
