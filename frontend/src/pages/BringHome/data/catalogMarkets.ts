import type { ShopCity, ShoppingDestination } from './types'

const w = (file: string) =>
  `https://commons.wikimedia.org/wiki/Special:FilePath/${encodeURIComponent(file)}?width=1200`

const REGION: Record<ShopCity, ShoppingDestination['region']> = {
  Hanoi: 'North',
  'Ninh Binh': 'North',
  Sapa: 'North',
  'Ha Giang': 'North',
  'Dong Van': 'North',
  'Ha Long': 'North',
  'Cat Ba': 'North',
  Hue: 'Central',
  'Da Nang': 'Central',
  'Hoi An': 'Central',
  'Nha Trang': 'Central',
  'Da Lat': 'Central',
  'Phong Nha': 'Central',
  'Ho Chi Minh City': 'South',
  'Phu Quoc': 'South',
  'Can Tho': 'South',
}

type Seed = {
  id: string
  name: string
  type: ShoppingDestination['type']
  city: ShopCity
  area: string
  files: string[]
  bestForItemIds: string[]
  bestForLabels: string[]
  crowdLevel: ShoppingDestination['crowdLevel']
  crowdLabel: string
  valueLevel: ShoppingDestination['valueLevel']
  touristFriendly: ShoppingDestination['touristFriendly']
  bargaining: ShoppingDestination['bargaining']
  priceRange: string
  whyRecommended: string
  featured?: boolean
  itineraryId?: string
}

function shop(seed: Seed): ShoppingDestination {
  return {
    id: seed.id,
    name: seed.name,
    type: seed.type,
    city: seed.city,
    region: REGION[seed.city],
    area: seed.area,
    images: seed.files.map(w),
    bestForItemIds: seed.bestForItemIds,
    bestForLabels: seed.bestForLabels,
    crowdLevel: seed.crowdLevel,
    crowdType: 'Typical',
    crowdLabel: seed.crowdLabel,
    valueLevel: seed.valueLevel,
    touristFriendly: seed.touristFriendly,
    bargaining: seed.bargaining,
    priceRange: seed.priceRange,
    rating: 4.2,
    openNow: true,
    openingHours: 'Hours vary — check Maps',
    hoursUnknown: true,
    distanceKm: null,
    whyRecommended: seed.whyRecommended,
    mapUrl: `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(`${seed.name}, ${seed.city}, Vietnam`)}`,
    featured: Boolean(seed.featured),
    itineraryId: seed.itineraryId ?? seed.id,
  }
}

