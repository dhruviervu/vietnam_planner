export function priceSymbols(level: 1 | 2 | 3 | 4): string {
  return '$'.repeat(level)
}

export function scoreRestaurant(
  r: Restaurant,
  dishId: string,
  sort: RestaurantSort,
): number {
  const dishHit = r.specialityDishIds.includes(dishId) ? 40 : 0
  const rating = r.rating * 8
  const reviews = Math.min(r.reviewCount / 200, 20)
  const open = r.openNow ? 6 : 0
  const distance =
    r.distanceKm == null ? 2 : Math.max(0, 10 - r.distanceKm * 2)
  const value = (5 - r.priceLevel) * 3
  const featured = r.featured ? 4 : 0

  if (sort === 'highest-rated') return rating * 3 + dishHit
  if (sort === 'most-reviewed') return reviews * 3 + dishHit + rating
  if (sort === 'best-value') return value * 4 + dishHit + rating + open
  // best-for-dish
  return dishHit + rating + reviews + open + distance + value + featured
}

export function getRestaurantsForDish(
  dishId: string,
  city: FoodCity | 'All',
  sort: RestaurantSort,
  filters: RestaurantFilter,
): Restaurant[] {
  let list = RESTAURANTS.filter((r) => r.specialityDishIds.includes(dishId))
  if (city !== 'All') list = list.filter((r) => r.city === city)
  if (filters.openNow) list = list.filter((r) => r.openNow)
  if (filters.outdoorSeating) list = list.filter((r) => r.outdoorSeating)
  if (filters.servesAlcohol) list = list.filter((r) => r.servesAlcohol)

  return [...list].sort(
    (a, b) => scoreRestaurant(b, dishId, sort) - scoreRestaurant(a, dishId, sort),
  )
}

export function citiesForDish(dishId: string): FoodCity[] {
  const set = new Set(
    RESTAURANTS.filter((r) => r.specialityDishIds.includes(dishId)).map((r) => r.city),
  )
  return FOOD_CITIES.filter((c) => set.has(c))
}
