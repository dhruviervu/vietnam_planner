export function eventCoverImage(id: string, fallback: string): string {
  return EVENT_MEDIA[id]?.[0] ?? fallback
}

export function eventGallery(id: string, fallback: string): string[] {
  const gallery = EVENT_MEDIA[id] ?? []
  const seed = gallery.length ? gallery : [fallback]
  const out: string[] = []
  while (out.length < 16) {
    out.push(seed[out.length % seed.length] ?? fallback)
  }
  return out
}
