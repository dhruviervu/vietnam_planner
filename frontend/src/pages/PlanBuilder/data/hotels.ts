export function getHotelById(id: string) {
  return HOTELS.find((h) => h.id === id)
}

export function hotelsForBase(baseId: string) {
  return HOTELS.filter((h) => h.baseId === baseId)
}

export function hotelsForRegion(region: string) {
  return HOTELS.filter((h) => h.region === region)
}

