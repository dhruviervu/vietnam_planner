import type { Experience, ExperienceCategory, ExperiencePopularityTag, ExperienceSignal, PriceType, SignalLevel, TravelStyle } from '../types'
import { imagesFor } from './experienceImages'
import { EXTRA_EXPERIENCE_DRAFTS } from './experiencesExtra'
import { formatFromPrice, priceTypeFromLegacy } from '../lib/pricing'

type Draft = {
  id: string
  name: string
  region: string
  city: string
  category: ExperienceCategory
  seeds: string[]
  hook: string
  about: string
  whyGo: string
  cardSummary?: string
  popularityRank?: number
  popularityTag?: ExperiencePopularityTag
  rating: number
  reviewCount: number
  costUsd: number
  costLabel: string
  priceType?: PriceType
  durationHours: number
  durationLabel: string
  dna: string[]
  signal: ExperienceSignal
  crowdBase: SignalLevel
  slotQuality: { morning: SignalLevel; afternoon: SignalLevel; evening: SignalLevel }
  accessibilityDetail: Experience['accessibilityDetail']
  hours: string
  bestTime: string
  paceAffinity: TravelStyle[]
  budgetBand: Experience['budgetBand']
  monthsIdeal: number[]
  relatedIds: string[]
  featured?: boolean
  hiddenGem?: boolean
  vietnamBest?: boolean
  seasonalNotes?: Experience['seasonalNotes']
  reviews?: Experience['reviews']
}

const SIGNAL_META: Record<
  ExperienceSignal,
  { emoji: string; label: string; blurb: string }
> = {
  'must-do': { emoji: '🔥', label: 'MUST DO', blurb: 'Defining Vietnam experience' },
  'vietnam-special': { emoji: '🇻🇳', label: 'VIETNAM SPECIAL', blurb: 'Unmistakably Vietnamese' },
  'hidden-gem': { emoji: '💎', label: 'HIDDEN GEM', blurb: 'Less visited, highly appreciated' },
  'picture-perfect': { emoji: '📸', label: 'PICTURE PERFECT', blurb: 'Exceptional scenery / photography' },
  'slow-scenic': { emoji: '🌿', label: 'SLOW & SCENIC', blurb: 'Best for a relaxed pace' },
  'local-life': { emoji: '🏮', label: 'LOCAL LIFE', blurb: 'Everyday Vietnam, lived locally' },
  adventure: { emoji: '⚡', label: 'ADVENTURE', blurb: 'Active / high-energy experience' },
}


function derivePopularityTag(d: Draft): ExperiencePopularityTag {
  if (d.popularityTag) return d.popularityTag
  if (d.signal === 'must-do' || d.featured) return 'Must do'
  if (d.hiddenGem || d.signal === 'hidden-gem') return 'Hidden gem'
  if (d.signal === 'vietnam-special' || d.signal === 'local-life') return 'Local favourite'
  if (d.signal === 'adventure' || d.signal === 'picture-perfect') return 'Unique'
  return 'Popular'
}

function deriveCardSummary(d: Draft): string {
  if (d.cardSummary) return d.cardSummary
  return `${d.about} ${d.whyGo} Expect roughly ${d.durationLabel.toLowerCase()}, with a typical starting cost around ${d.costLabel}.`
}

function build(d: Draft): Experience {
  const meta = SIGNAL_META[d.signal]
  const priceType = d.priceType ?? priceTypeFromLegacy(d.costUsd, d.costLabel)
  const price = d.costUsd
  return {
    ...d,
    images: imagesFor(d.id, d.seeds),
    price,
    priceType,
    costUsd: price,
    costLabel: formatFromPrice(price, priceType),
    popularity: d.hiddenGem
      ? 'Less crowded favorite'
      : d.featured
        ? 'Highly visited'
        : 'Popular with travelers',
    popularityRank: d.popularityRank ?? 50,
    popularityTag: derivePopularityTag(d),
    cardSummary: deriveCardSummary(d),
    accessibility: `${d.accessibilityDetail.wheelchair} · ${d.accessibilityDetail.walking}`,
    tags: d.dna,
    signalEmoji: meta.emoji,
    signalLabel: meta.label,
    signalBlurb: meta.blurb,
    seasonalNotes: d.seasonalNotes ?? [
      {
        months: [10, 11, 3],
        label: 'Prime months',
        weather: 'Favorable',
        crowds: 'Moderate',
        note: 'Strong overall window',
      },
      {
        months: [7, 8],
        label: 'Wet season',
        weather: 'Variable / rainier',
        crowds: 'Moderate',
        note: 'Lush landscapes, more weather risk',
      },
    ],
    reviews: d.reviews ?? [
      { author: 'Maya', rating: 5, text: 'Exactly as hoped — unforgettable.' },
      { author: 'Chris', rating: 4, text: 'Worth planning a full half-day around.' },
    ],
  }
}

