export type SightSection = (typeof SIGHT_SECTION_ORDER)[number]

export function sightSectionsPresent(items: { sightSection?: string }[]): string[] {
  const present = new Set(items.map((i) => i.sightSection).filter(Boolean) as string[])
  const ordered = SIGHT_SECTION_ORDER.filter((s) => present.has(s))
  const extras = [...present].filter((s) => !SIGHT_SECTION_ORDER.includes(s as SightSection))
  return [...ordered, ...extras]
}
