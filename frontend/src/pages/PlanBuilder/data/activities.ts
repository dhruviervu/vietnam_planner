export type ActivityKind =
  | 'class'
  | 'music'
  | 'dance'
  | 'sport'
  | 'beach'
  | 'workshop'
  | 'food'
  | 'community'
  | 'adventure'
  | 'craft'

export type ActivityPopularityTag =
  | 'Must do'
  | 'Popular'
  | 'Free time'
  | 'Local favourite'
  | 'Unique'

export type CityActivity = {
  id: string
  /** Matches EXPLORE_CITIES id */
  cityId: string
  cityName: string
  name: string
  /**
   * Shared identity for variants of the same place. Two sights with the same
   * `groupId` are never scheduled on the same day.
   */
  groupId?: string
  /** When this sight belongs in the day. Defaults to ANY when unset. */
  timePreference?: TimePreference
  kind: ActivityKind
  kindLabel: string
  hook: string
  summary: string
  /** Longer card blurb (2–4 sentences) */
  cardSummary: string
  /** ~200-word story for the detail page */
  about: string
  whyGo: string
  durationLabel: string
  priceFromUsd: number | null
  priceLabel: string
  bestFor: string[]
  vibe: string
  /** Primary image (cards + bag thumbs) */
  image: string
  images: string[]
  popularityTag: ActivityPopularityTag
  signalEmoji: string
  signalLabel: string
  tags: string[]
  bestTime: string
  hours: string
  rating: number
}

