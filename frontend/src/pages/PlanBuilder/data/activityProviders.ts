export function getActivityProviders(activity: CityActivity): ActivityProvider[] {
  if (!isBookableActivity(activity)) return []
  const listed = PROVIDERS[activity.id]
  if (listed && listed.length >= 2) return listed
  const q = `${activity.cityName} ${activity.name}`
  return pair(
    activity.id,
    [
      `${activity.cityName} local operator`,
      `A small booked session for ${activity.name.toLowerCase()} — confirm inclusions before you pay.`,
      activity.priceLabel,
      activity.durationLabel,
      4.7,
      240,
      gyg(q),
    ],
    [
      `${activity.cityName} specialist`,
      `Another listed option for the same activity. Compare group size and what’s included.`,
      activity.priceLabel,
      activity.durationLabel,
      4.6,
      180,
      klook(q),
    ],
  )
}
