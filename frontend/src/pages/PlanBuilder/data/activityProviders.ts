import type { CityActivity } from './activities'

export type ActivityProvider = {
  id: string
  name: string
  description: string
  priceLabel: string
  durationLabel: string
  rating: number
  reviewCount: number
  bookingUrl: string
}

const DROP_IN = new Set([
  'hn-tai-chi-lake',
  'hl-beach-volley',
  'hg-homestay-dance',
  'hg-market-day',
  'sp-evening-song',
  'ha-an-bang-play',
  'dn-beach-football',
  'mk-homestay-fish',
  'pq-beach-volley',
  'pq-beach-drum',
])

export function isBookableActivity(activity: CityActivity) {
  return !DROP_IN.has(activity.id)
}

const gyg = (q: string) => `https://www.getyourguide.com/s/?q=${encodeURIComponent(q)}`
const klook = (q: string) =>
  `https://www.klook.com/en-US/search/?query=${encodeURIComponent(q)}`
const viator = (q: string) =>
  `https://www.viator.com/searchResults/all?text=${encodeURIComponent(q)}`

type Seed = [string, string, string, string, number, number, string]

function pair(id: string, a: Seed, b: Seed): ActivityProvider[] {
  return [
    {
      id: `${id}-a`,
      name: a[0],
      description: a[1],
      priceLabel: a[2],
      durationLabel: a[3],
      rating: a[4],
      reviewCount: a[5],
      bookingUrl: a[6],
    },
    {
      id: `${id}-b`,
      name: b[0],
      description: b[1],
      priceLabel: b[2],
      durationLabel: b[3],
      rating: b[4],
      reviewCount: b[5],
      bookingUrl: b[6],
    },
  ]
}

