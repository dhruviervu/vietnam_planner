function pair(a: string, b: string, mode: NetworkMode, rest: Omit<HubConnection, 'id' | 'originHubId' | 'destinationHubId' | 'mode'>): HubConnection[] {
  const base = { mode, ...rest }
  return [
    {
      id: `${mode}-${a}-${b}`,
      originHubId: a,
      destinationHubId: b,
      ...base,
    },
    {
      id: `${mode}-${b}-${a}`,
      originHubId: b,
      destinationHubId: a,
      ...base,
    },
  ]
}

