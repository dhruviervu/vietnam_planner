export function getHub(id: string | null | undefined) {
  if (!id) return null
  return TRANSPORT_HUBS.find((h) => h.id === id) ?? null
}

export function getTopology(placeId: PlaceId) {
  return LOCATION_TOPOLOGY[placeId] ?? null
}

export function findHubConnection(originHubId: string, destinationHubId: string, mode: NetworkMode) {
  return (
    HUB_CONNECTIONS.find(
      (c) =>
        c.mode === mode &&
        c.originHubId === originHubId &&
        c.destinationHubId === destinationHubId &&
        c.verificationStatus !== 'unknown',
    ) ?? null
  )
}

export function findGroundLink(fromPlaceId: PlaceId, toHubId: string) {
  return GROUND_LINKS.find((g) => g.fromPlaceId === fromPlaceId && g.toHubId === toHubId) ?? null
}
