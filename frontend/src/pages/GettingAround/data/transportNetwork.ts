import type { PlaceId } from './types'

export type VerificationStatus = 'verified' | 'curated' | 'estimated' | 'unknown'
export type HubType = 'airport' | 'rail' | 'coach' | 'ferry' | 'interchange'
export type HubRelevance = 'primary' | 'secondary' | 'relevant'
export type NetworkMode = 'flight' | 'train' | 'coach' | 'private-driver' | 'shared-transfer' | 'ferry' | 'fast-boat' | 'ground'

export type LocationTopology = {
  placeId: PlaceId
  isIsland: boolean
  isMainland: boolean
  hasRoadAccess: boolean
  hasBridgeAccess: boolean
  hasFerryAccess: boolean
  /** Commercial passenger airport in/near the place */
  hasFlightAccess: boolean
  /** Useful passenger rail station for long-distance travel */
  hasRailAccess: boolean
  primaryAirportHubId: string | null
  primaryRailHubId: string | null
  primaryCoachHubId: string | null
  primaryFerryPortId: string | null
  verificationStatus: VerificationStatus
}

export type TransportHub = {
  id: string
  name: string
  /** Place used for map context / snapping */
  placeId: PlaceId
  type: HubType
  relevance: HubRelevance
  lat: number
  lng: number
  verificationStatus: VerificationStatus
}

export type HubConnection = {
  id: string
  originHubId: string
  destinationHubId: string
  mode: NetworkMode
  direct: boolean
  typicalMinutes: [number, number] | null
  typicalCostUsd: [number, number] | null
  notes: string
  verificationStatus: VerificationStatus
}

export type GroundLink = {
  id: string
  fromPlaceId: PlaceId
  toHubId: string
  mode: 'ground' | 'shared-transfer' | 'private-driver' | 'coach'
  typicalMinutes: [number, number]
  typicalCostUsd: [number, number]
  notes: string
  verificationStatus: VerificationStatus
}

