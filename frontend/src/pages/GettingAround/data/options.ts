export function optionsForMode(modeId: TransportModeId): TransportOption[] {
  return SEEDS.filter((s) => s.modeId === modeId).map((s, i) => ({
    ...s,
    id: `${modeId}-${i}`,
  }))
}

export function getBookingProviders(option: TransportOption): BookingProvider[] {
  return [
    {
      id: `${option.id}-direct`,
      name: option.provider,
      priceLabel: option.priceLabel,
      rating: option.rating,
      cancellation: option.cancellation,
      luggage: option.luggage,
      availability: option.availability,
      bookingUrl: option.bookingUrl,
      providerUrl: option.providerUrl,
      source: option.source,
    },
    {
      id: `${option.id}-compare`,
      name: 'Compare similar services',
      priceLabel: `Around ${option.priceLabel.replace('From ', '')}`,
      rating: Math.max(3.8, option.rating - 0.2),
      cancellation: 'Varies by provider',
      luggage: option.luggage,
      availability: 'Check live inventory',
      bookingUrl: option.bookingUrl || 'https://12go.asia/en/travel/vietnam',
      providerUrl: option.providerUrl,
      source: 'Comparison search',
    },
  ]
}
