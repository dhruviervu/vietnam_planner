export function pointsForCity(cityId: PlaceId) {
  return URBAN_POINTS.filter((p) => p.cityId === cityId)
}

export function getUrbanPoint(id: string | null) {
  if (!id) return null
  return URBAN_POINTS.find((p) => p.id === id) ?? null
}

export function googleMapsDirectionsUrl(
  a: { lat: number; lng: number; label?: string },
  b: { lat: number; lng: number; label?: string },
) {
  const origin = `${a.lat},${a.lng}`
  const destination = `${b.lat},${b.lng}`
  return `https://www.google.com/maps/dir/?api=1&origin=${encodeURIComponent(origin)}&destination=${encodeURIComponent(destination)}`
}
