export function templatesForSection(section: ItineraryTemplate['section']) {
  return ITINERARY_TEMPLATES.filter((t) => t.section === section)
}

export function durationLabel(template: ItineraryTemplate) {
  if (template.minDays === template.maxDays) return `${template.minDays} days`
  return `${template.minDays}–${template.maxDays} days`
}

export function cityArc(cities: string[]) {
  return cities.join(' → ')
}

const TEMPLATE_BY_ID = new Map(ITINERARY_TEMPLATES.map((t) => [t.id, t]))

export function getTemplateById(id: string) {
  return TEMPLATE_BY_ID.get(id)
}
