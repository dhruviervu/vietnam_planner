/**
 * Rough, irregular cluster outline — used only when a curated ring is missing.
 * Prefer CLUSTER_POLYGONS for place-accurate shapes.
 */
const box = (west: number, south: number, east: number, north: number): GeoRing => {
  const cx = (west + east) / 2
  const cy = (south + north) / 2
  const hw = (east - west) / 2
  const hh = (north - south) / 2
  const seed = Math.abs(west * 17 + north * 31)
  const pts: [number, number][] = []
  const n = 12
  for (let i = 0; i < n; i++) {
    const a = (i / n) * Math.PI * 2 - Math.PI / 2
    const ux = Math.cos(a)
    const uy = Math.sin(a)
    const squareR = 1 / Math.max(Math.abs(ux), Math.abs(uy), 0.001)
    const blend = 0.62 + 0.18 * Math.sin(seed + i * 1.7)
    const r = blend * squareR + (1 - blend)
    const wobble = 1 + 0.12 * Math.sin(seed * 0.7 + i * 2.3)
    pts.push([cx + ux * hw * r * wobble, cy + uy * hh * r * wobble])
  }
  pts.push(pts[0])
  return pts
}

