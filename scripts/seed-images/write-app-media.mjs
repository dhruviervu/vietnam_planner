import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.dirname(fileURLToPath(import.meta.url))
const jsonPath = path.resolve(ROOT, '../../frontend/src/pages/PlanBuilder/data/experienceMedia.json')
const tsPath = path.resolve(ROOT, '../../frontend/src/pages/PlanBuilder/data/experienceMedia.ts')
const media = JSON.parse(fs.readFileSync(jsonPath, 'utf8'))
const body = `/** Auto-generated by scripts/seed-images/seed-images.ts — do not edit by hand. */
export type ExperienceVideo = {
  youtubeId: string
  title?: string
}

export type ExperienceMedia = {
  photos: string[]
  videos: ExperienceVideo[]
}

export const EXPERIENCE_MEDIA: Record<string, ExperienceMedia> = ${JSON.stringify(media, null, 2)}

export function getExperienceMedia(id: string): ExperienceMedia | null {
  return EXPERIENCE_MEDIA[id] ?? null
}
`
fs.writeFileSync(tsPath, body)
console.log('Wrote', tsPath, Object.keys(media).length, 'sights')
